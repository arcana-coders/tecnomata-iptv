_override = None


def force_language_override(code):
    """Fuerza el idioma (usado en --demo) sin persistir en QSettings."""
    global _override
    _override = code if code in LANGUAGES else None


def current_language():
    if _override:
        return _override
    value = QSettings('Tecnomata', 'IPTV').value('language', 'es')
    return value if value in LANGUAGES else 'es'


def set_language(code):
    if code in LANGUAGES:
        QSettings('Tecnomata', 'IPTV').setValue('language', code)


def t(key, **kwargs):
    entry = STRINGS.get(key)
    if not entry:
        return key
    text = entry.get(current_language(), entry.get('es', key))
    return text.format(**kwargs) if kwargs else text
